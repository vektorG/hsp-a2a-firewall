import 'dotenv/config';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { hspToolSchemas } from '../src/mcp/schemas.js';

const url = process.env.HSP_MCP_URL ?? 'https://mcp-qa.hashkeymerchant.com/';
const root = process.cwd();
const outputDirectory = path.join(root, 'docs');
const schemasPath = path.join(outputDirectory, 'live-schemas.json');
const diffPath = path.join(outputDirectory, 'schema-diff.md');
const mock = process.argv.includes('--mock');

interface Dump {
  fetchedAt: string;
  url: string;
  source: 'live' | 'mock';
  tools: Array<{ name: string; description?: string; [key: string]: unknown }>;
}

function localToolNames(): string[] {
  return Object.keys(hspToolSchemas);
}

function renderDiff(dump: Dump): string {
  const liveNames = new Set(dump.tools.map((tool) => tool.name));
  const rows = localToolNames().map(
    (name) => `| \`${name}\` | ${liveNames.has(name) ? 'yes' : 'no'} |`,
  );

  return `# HSP MCP schema diff

Generated: ${dump.fetchedAt}
Source: ${dump.source}
Endpoint: ${dump.url}

This file is generated by \`npm run mcp:dump\` alongside \`docs/live-schemas.json\`.
The JSON dump is the raw \`tools/list\` payload; this document is the human
checklist for reconciling the live payload with \`src/mcp/schemas.ts\`.

## Token configuration (guide: \`tokens[]\`)

The guide resolves chain configuration as an **array** (\`tokens[]\`). The local
schema keeps the single-token convenience field \`token\` for existing callers,
accepts \`tokens[]\`, and preserves every field through \`.passthrough()\`.
\`LiveHspMcpClient\` normalizes \`tokens[0]\` into \`token\` before validation when
the live server omits the convenience field.

| Field | Local schema | Live guide | Notes |
| --- | --- | --- | --- |
| \`token\` | required after normalization | convenience only | Kept for compatibility |
| \`tokens\` | optional \`TokenConfig[]\` | canonical array | Never dropped |
| \`tokens[].address\` | required EVM address | expected | Runtime-only (R5) |
| \`tokens[].symbol\` | required string | expected | Display only |
| \`tokens[].decimals\` | required integer | expected | Display only |
| \`permit2\` | optional EVM address | when Permit2 rail | Drives \`npm run approve\` |
| \`payment_protocol\` | optional string | expected | \`EIP-3009\` => no approve |

## Tool catalogue

| Tool | Present in live dump |
| --- | --- |
${rows.join('\n')}

## Field-level checklist

- [ ] \`get_chain_config\`: live uses \`tokens[]\`; confirm array length and that
      \`permit2\` / \`payment_protocol\` are populated.
- [ ] \`create_order\`: confirm whether \`pay_to\` is accepted at order creation and
      that every returned field (including unknown extras) is preserved.
- [ ] \`prepare_payment\`: confirm \`eip712\`, \`payment_payload\` and
      \`payment_mandate_contents\` and echo every unknown field into
      \`finalize_payment\`.
- [ ] \`finalize_payment\`: confirm which prepare fields must be echoed back.
- [ ] \`submit_payment\`: confirm \`tx_signature\` nullability before broadcast.
- [ ] \`query_payment\`: confirm \`attribution_verified\` semantics and every
      polling status.
- [ ] \`get_order\` / \`estimate_fee\`: confirm shapes not yet exercised live.

## How to refresh

\`\`\`bash
npm run mcp:dump          # live gateway
npm run mcp:dump -- --mock  # offline template, no network calls
\`\`\`
`;
}

async function liveDump(): Promise<Dump> {
  const client = new Client({
    name: 'hsp-a2a-firewall',
    version: '0.1.0',
  });
  const transport = new StreamableHTTPClientTransport(new URL(url));

  try {
    await client.connect(transport);
    const listed = await client.listTools();
    return {
      fetchedAt: new Date().toISOString(),
      url,
      source: 'live',
      tools: listed.tools as Dump['tools'],
    };
  } finally {
    await client.close();
  }
}

function mockDump(): Dump {
  return {
    fetchedAt: new Date().toISOString(),
    url,
    source: 'mock',
    tools: localToolNames().map((name) => ({
      name,
      description: 'Local schema placeholder (mock dump, no live call).',
    })),
  };
}

async function main(): Promise<void> {
  const dump = mock ? mockDump() : await liveDump();

  mkdirSync(outputDirectory, { recursive: true });
  writeFileSync(schemasPath, `${JSON.stringify(dump, null, 2)}\n`, 'utf8');
  writeFileSync(diffPath, renderDiff(dump), 'utf8');

  console.log(
    `Dumped ${dump.tools.length} tool schema(s) (${dump.source}) -> ${path.relative(root, schemasPath)}`,
  );
  console.log(`Wrote schema diff template -> ${path.relative(root, diffPath)}`);
}

main().catch((error: unknown) => {
  console.error(
    'Failed to dump HSP MCP schemas:',
    error instanceof Error ? error.message : error,
  );
  process.exitCode = 1;
});
